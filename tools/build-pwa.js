'use strict';
/** Generates frontend/precache-manifest.js (every shell file + a content hash version) so the service worker never goes stale. */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..', 'frontend'), SKIP = new Set(['service-worker.js', 'precache-manifest.js', 'package.json']);
function walk(dir, out = []) { fs.readdirSync(dir, { withFileTypes: true }).forEach((e) => { const p = path.join(dir, e.name); if (e.isDirectory()) walk(p, out); else out.push(p); }); return out; }
function compute() {
  const files = walk(ROOT).map((p) => path.relative(ROOT, p).split(path.sep).join('/')).filter((f) => !SKIP.has(f) && !f.endsWith('.map') && !f.endsWith('LICENSE')).sort();
  const hash = crypto.createHash('sha256'); files.forEach((f) => { hash.update(f); hash.update(fs.readFileSync(path.join(ROOT, f))); });
  const list = ['./'].concat(files.map((f) => './' + f));
  const body = `/* GENERATED by tools/build-pwa.js - do not edit. */\nself.GOPS_PRECACHE = ${JSON.stringify({ version: hash.digest('hex').slice(0, 12), files: list }, null, 2)};\n`;
  return { body, list };
}
function build() { const r = compute(); fs.writeFileSync(path.join(ROOT, 'precache-manifest.js'), r.body); return r.list; }
if (require.main === module) console.log('precached files:', build().length);
module.exports = { build, compute };
